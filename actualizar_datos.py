def calcular_rsi(close, periodo=14):
    # Wilder's Smoothing (RMA) — igual a TradingView
    delta = close.diff()
    ganancia = delta.clip(lower=0)
    perdida = (-delta.clip(upper=0))
    alpha = 1 / periodo
    avg_gan = ganancia.ewm(alpha=alpha, min_periods=periodo, adjust=False).mean()
    avg_per = perdida.ewm(alpha=alpha, min_periods=periodo, adjust=False).mean()
    rs = avg_gan / avg_per
    return round((100 - (100 / (1 + rs))).iloc[-1], 2)

def calcular_volatilidad_relativa(close, high, low, ruedas_corto=5, ruedas_largo=252):
    """
    Promedio del rango diario H-L/Close de los últimos 5 días vs histórico 1 año.
    Captura velas amplias individuales (ej: +20% en un día) y semanas extendidas.
    < 1 = velas más estrechas que de costumbre (comprimido)
    > 1 = velas más anchas que de costumbre (extendido/volátil)
    """
    if len(close) < ruedas_largo + ruedas_corto:
        return None
    rango_pct = ((high - low) / close).dropna()
    if len(rango_pct) < ruedas_largo:
        return None
    avg_5d   = rango_pct.tail(ruedas_corto).mean()
    avg_hist = rango_pct.tail(ruedas_largo).mean()
    if avg_hist == 0:
        return None
    return round(avg_5d / avg_hist, 2)

def calcular_volumen_inusual(volume, ruedas=20):
    if len(volume) < ruedas + 1:
        return None
    vol_hoy      = volume.iloc[-1]
    vol_promedio = volume.iloc[-ruedas-1:-1].mean()
    if vol_promedio == 0:
        return None
    return round((vol_hoy / vol_promedio - 1) * 100, 2)

RS_LOOKBACK_MIN = 60  # ~3 meses -- por debajo de esto el percentrank no es confiable

def calcular_rs_score(close_ticker, close_spy, periodo_sma=50, lookback=252):
    df = pd.DataFrame({"ticker": close_ticker, "spy": close_spy}).dropna()
    # Historial corto (spin-offs/IPOs recientes, ej. SNDK desde 2/2025): en vez
    # de devolver todo None y dejar el pilar de Fuerza Relativa ciego durante
    # el primer año de cotizacion, usar como lookback todo lo disponible.
    # Se reserva margen de 22 ruedas para que "ayer/semana/mes" tambien caigan
    # dentro de la ventana valida del percentrank (si no, quedan en NaN aunque
    # el valor de hoy si se calcule). Piso de RS_LOOKBACK_MIN ruedas para que
    # el percentrank siga siendo estadisticamente razonable.
    lb = min(lookback, len(df) - 22)
    if lb < RS_LOOKBACK_MIN:
        return None, None, None, None, None, None, None, None, None

    df["fr"]     = df["ticker"] / df["spy"]
    df["sma_fr"] = df["fr"].rolling(window=periodo_sma).mean()

    def percentrank_tv(series, length):
        """
        Replica exacta de ta.percentrank de TradingView:
        cuenta cuántos de los últimos 'length' valores anteriores
        son MENORES al valor actual (excluye el valor actual)
        """
        scores = []
        arr = series.values
        for i in range(len(arr)):
            if i < length:
                scores.append(np.nan)
            else:
                ventana = arr[i-length:i]
                actual  = arr[i]
                rank    = (ventana < actual).sum() / length * 100
                scores.append(round(rank, 2))
        return pd.Series(scores, index=series.index)

    df["rs_score"] = percentrank_tv(df["fr"], lb)

    ultimo = df.iloc[-1]
    ayer   = df.iloc[-2]
    semana = df.iloc[-6]  if len(df) >= 6  else df.iloc[0]
    mes    = df.iloc[-22] if len(df) >= 22 else df.iloc[0]

    sobre_sma = "✅ Sí" if ultimo["fr"] > ultimo["sma_fr"] else "❌ No"

    return (
        round(ultimo["rs_score"], 1),
        round(ayer["rs_score"],   1),
        round(semana["rs_score"], 1),
        round(mes["rs_score"],    1),
        sobre_sma,
        round(float(ultimo["fr"]), 6),
        round(float(ayer["fr"]),   6),
        round(float(semana["fr"]), 6),
        round(float(mes["fr"]),    6),
    )

def rs_score_series(close_ticker, close_spy, lookback=252):
    """Serie completa de RS Score (percentrank de ticker/spy), dia por dia.
    Standalone (no comparte tupla con calcular_rs_score) para no tocar esa
    funcion ya probada en produccion. Usada para leer el RS Score en una
    rueda especifica del pasado (ej. el dia de contacto con la EMA200).
    Mismo lookback dinamico que calcular_rs_score() para tickers con poco
    historial (ver RS_LOOKBACK_MIN)."""
    df = pd.DataFrame({"ticker": close_ticker, "spy": close_spy}).dropna()
    lb = min(lookback, len(df) - 1)
    if lb < RS_LOOKBACK_MIN:
        return None
    fr = df["ticker"] / df["spy"]
    arr = fr.values
    scores = []
    for i in range(len(arr)):
        if i < lb:
            scores.append(np.nan)
        else:
            ventana = arr[i-lb:i]
            rank = (ventana < arr[i]).sum() / lb * 100
            scores.append(round(rank, 2))
    return pd.Series(scores, index=fr.index)

def atr14_pct(df):
    """ATR de 14 ruedas expresado como % del precio actual."""
    if df is None or len(df) < 15:
        return None
    try:
        high  = df['High']
        low   = df['Low']
        close = df['Close']
        prev  = close.shift(1)
        tr = pd.concat([
            high - low,
            (high - prev).abs(),
            (low  - prev).abs()
        ], axis=1).max(axis=1)
        atr14  = tr.tail(14).mean()
        precio = close.iloc[-1]
        if precio <= 0:
            return None
        return round(float(atr14 / precio * 100), 4)
    except:
        return None

def vol_anual_pct(df):
    """Volatilidad histórica anualizada (252 ruedas) expresada como %."""
    if df is None or len(df) < 20:
        return None
    try:
        rets = df['Close'].pct_change().dropna()
        if len(rets) < 20:
            return None
        return round(float(rets.std() * (252 ** 0.5) * 100), 4)
    except:
        return None


def _atr14_series(df):
    """Serie completa de ATR14 (True Range promedio de 14 ruedas), no solo el ultimo valor."""
    try:
        high, low, close = df['High'], df['Low'], df['Close']
        prev = close.shift(1)
        tr = pd.concat([
            high - low,
            (high - prev).abs(),
            (low  - prev).abs()
        ], axis=1).max(axis=1)
        return tr.rolling(14).mean()
    except Exception:
        return None


def avance_pico_15r(df):
    """Avance Pico 15r % — estiramiento reciente medido contra el PICO de la
    ventana, no contra el cierre de hoy. Motivo (caso CVX): si el papel subió
    y corrigió parte en las últimas ruedas, medir cierre-a-cierre esconde el
    estiramiento real; contra el pico queda capturado. cierre_base usa el menor
    entre el cierre de hace 15 ruedas y el mínimo de cierre de la ventana, para
    anclar bien la base de recuperaciones en V. Reemplaza a la vieja
    'Var 10 Ruedas %' (Warren Score v2.3)."""
    if df is None or len(df) < 16:
        return None
    try:
        close, high = df['Close'], df['High']
        pico_15r          = high.tail(15).max()
        cierre_hace_15    = close.iloc[-16]
        min_close_ventana = close.tail(15).min()
        cierre_base       = min(cierre_hace_15, min_close_ventana)
        if cierre_base <= 0:
            return None
        return round(float((pico_15r / cierre_base - 1) * 100), 2)
    except Exception:
        return None


def choppiness_eficiencia(df):
    """Choppiness (ventana corta, Warren Score v4.1) y Eficiencia (Kaufman
    ER, 10 ruedas, SIN CAMBIOS). Detecta 'volatilidad sin dirección' --
    velas grandes sin avance neto, firma de posible distribución (Warren
    Score v2.3, caso VOD).

    Choppiness: mediana del True Range de las últimas 4 ruedas vs mediana
    del TR de las 20 ruedas previas a esas, sin solapamiento. La
    definición anterior (ATR14% de hoy vs ATR14% de hace 20 ruedas, ambos
    promedios de 14 ruedas) estaba estructuralmente incapacitada para
    detectar una expansión de volatilidad de 3-5 ruedas -- hacían falta
    ~13 velas consecutivas grandes para mover el promedio de 14 lo
    suficiente; para entonces la corrección ya había ocurrido. La
    ventana corta reacciona en 3-4 ruedas. Medianas (no promedios) en
    ambos lados para que un solo día extremo no dispare la señal ni
    distorsione la referencia -- mismo criterio que
    contraccion_volatilidad(). Ratio entre dos medianas del mismo TR en
    USD: no hace falta normalizar por precio, se cancela."""
    if df is None or len(df) < 24:
        return {'Choppiness': None, 'Eficiencia 10d': None}
    try:
        close = df['Close']
        high, low = df['High'], df['Low']
        prev = close.shift(1)
        tr = pd.concat([
            high - low,
            (high - prev).abs(),
            (low  - prev).abs()
        ], axis=1).max(axis=1).dropna()
        if len(tr) < 24:
            choppiness = None
        else:
            t = tr.tail(24).tolist()
            reciente   = float(pd.Series(t[-4:]).median())
            referencia = float(pd.Series(t[-24:-4]).median())
            choppiness = round(reciente / referencia, 4) if referencia > 0 else None

        cambio_neto = abs(close.iloc[-1] - close.iloc[-11])
        recorrido   = close.tail(11).diff().abs().sum()
        eficiencia  = round(float(cambio_neto / recorrido), 4) if recorrido > 0 else None

        return {'Choppiness': choppiness, 'Eficiencia 10d': eficiencia}
    except Exception:
        return {'Choppiness': None, 'Eficiencia 10d': None}


# ── Panel "Regreso a la EMA200" — visitas raras a la media de largo plazo ──
EMA200_CERCA_ATR = 2.0   # "cerca de la EMA200" = |precio - EMA200| <= CERCA_ATR x ATR14
EMA200_RACHA_MIN = 80    # ruedas minimas de alejamiento previo para que la visita sea "rara" (~4 meses)
EMA200_VENTANA   = 15    # la visita es "actual" si ocurrio dentro de las ultimas 15 ruedas

def visita_ema200(close, ema200, atr14, cerca_atr=EMA200_CERCA_ATR, racha_min=EMA200_RACHA_MIN, ventana=EMA200_VENTANA):
    """
    Detecta visitas raras a la EMA200: un acercamiento actual precedido por
    una racha larga de alejamiento (no la frecuencia anual, que solo informa).
    close/ema200/atr14: arrays o series alineados, mismo largo (>= 260 ruedas).
    """
    try:
        c = np.asarray(close, dtype=float)
        e = np.asarray(ema200, dtype=float)
        a = np.asarray(atr14, dtype=float)
        n = len(c)
        if n < 260:
            return None
        if np.isnan(a[-1]) or a[-1] <= 0:
            return None  # ATR no computable -> el umbral "cerca" tampoco lo es

        valid = ~np.isnan(a) & (a > 0)
        cerca = np.zeros(n, dtype=bool)
        cerca[valid] = np.abs(c[valid] - e[valid]) <= cerca_atr * a[valid]

        freq = round(float(cerca[-252:].mean() * 100), 1) if n >= 252 else round(float(cerca.mean() * 100), 1)
        dist_atrs = round(float((c[-1] - e[-1]) / a[-1]), 2)

        idx_visitas = [i for i in range(max(0, n - ventana), n) if cerca[i]]
        if not idx_visitas:
            return {'visita': False, 'racha': None, 'freq': freq, 'dist_atrs': dist_atrs}

        # inicio del acercamiento actual: retroceder mientras siga "cerca"
        inicio = idx_visitas[0]
        while inicio - 1 >= 0 and cerca[inicio - 1]:
            inicio -= 1

        # racha de alejamiento previa al acercamiento actual
        racha = 0
        j = inicio - 1
        while j >= 0 and not cerca[j]:
            racha += 1
            j -= 1
        # si la racha llega hasta el principio de la serie disponible, se toma tal cual (no None)

        return {'visita': racha >= racha_min, 'racha': racha, 'freq': freq, 'dist_atrs': dist_atrs}
    except Exception:
        return None

# ── EMA200 Reversal Score — clímax de volumen + repunte de RS en el contacto ──
EMA200R_CONTACTO_PCT  = 1.0   # "en contacto" = distancia a la EMA200 <= 1% del precio
EMA200R_VENTANA       = 10    # el contacto cuenta si ocurrió en las últimas 10 ruedas
EMA200R_CLIMAX_MARGEN = 3     # la vela de clímax se busca en contacto ± 3 ruedas

def ema200_reversal_features(hist, ema200_series, rs_series):
    """
    Features para el EMA200 Reversal Score (calculado en el frontend):
    - contacto_ruedas: ruedas atrás (0=hoy) del contacto más reciente con la
      EMA200 (distancia <= 1% del precio) dentro de las últimas 10 ruedas.
    - racha_previa: ruedas que estuvo lejos de la EMA200 (> 1%) antes de que
      empezara este acercamiento (cuanto más rara la visita, más vale).
    - dist_hace20: Dist EMA200 % de hace 20 ruedas (para ver si "venía de arriba").
    - climax_vol_ratio / climax_pos_cierre: la vela de mayor volumen dentro de
      contacto ± 3 ruedas (vela de clímax/absorción) y su cierre relativo a su rango.
    - rs_en_contacto: RS Score en la rueda del contacto.
    - precio_sobre_climax: si el precio actual ya superó el máximo de la vela de clímax.
    Devuelve None si no hay suficiente historia o no hubo contacto en ventana.
    """
    try:
        close  = hist['Close'].values
        high   = hist['High'].values
        low    = hist['Low'].values
        volume = hist['Volume'].values
        ema200 = ema200_series.values
        n = len(close)
        if n < 260 or rs_series is None:
            return None

        valid = ~np.isnan(ema200) & (ema200 != 0)
        cerca = np.zeros(n, dtype=bool)
        cerca[valid] = np.abs(close[valid] - ema200[valid]) / np.abs(ema200[valid]) * 100 <= EMA200R_CONTACTO_PCT

        contacto_ruedas = None
        for ago in range(EMA200R_VENTANA):
            idx = n - 1 - ago
            if idx >= 0 and cerca[idx]:
                contacto_ruedas = ago
                break
        if contacto_ruedas is None:
            return None

        contacto_idx = n - 1 - contacto_ruedas

        # racha de alejamiento previa al acercamiento actual (mismo criterio
        # que visita_ema200, pero con "cerca" definido en % en vez de ATRs)
        inicio = contacto_idx
        while inicio - 1 >= 0 and cerca[inicio - 1]:
            inicio -= 1
        racha_previa = 0
        j = inicio - 1
        while j >= 0 and not cerca[j]:
            racha_previa += 1
            j -= 1

        idx20 = n - 21
        dist_hace20 = None
        if idx20 >= 0 and not np.isnan(ema200[idx20]) and ema200[idx20] != 0:
            dist_hace20 = round(float((close[idx20] - ema200[idx20]) / ema200[idx20] * 100), 2)

        lo = max(0, contacto_idx - EMA200R_CLIMAX_MARGEN)
        hi = min(n - 1, contacto_idx + EMA200R_CLIMAX_MARGEN)
        climax_idx = max(range(lo, hi + 1), key=lambda i: volume[i])

        climax_vol_ratio = None
        if climax_idx >= 20:
            vol_prom20 = float(np.mean(volume[climax_idx-20:climax_idx]))
            if vol_prom20 > 0:
                climax_vol_ratio = round(float(volume[climax_idx]) / vol_prom20, 2)

        rango = high[climax_idx] - low[climax_idx]
        climax_pos_cierre = 0.5 if rango <= 0 else round(float((close[climax_idx] - low[climax_idx]) / rango), 3)

        rs_en_contacto = None
        pos_rs = len(rs_series) - 1 - contacto_ruedas
        if pos_rs >= 0:
            val = rs_series.iloc[pos_rs]
            if not pd.isna(val):
                rs_en_contacto = round(float(val), 1)

        precio_sobre_climax = bool(close[-1] > high[climax_idx])

        return {
            'contacto_ruedas':     contacto_ruedas,
            'racha_previa':        racha_previa,
            'dist_hace20':         dist_hace20,
            'climax_vol_ratio':    climax_vol_ratio,
            'climax_pos_cierre':   climax_pos_cierre,
            'rs_en_contacto':      rs_en_contacto,
            'precio_sobre_climax': precio_sobre_climax,
        }
    except Exception:
        return None

def detectar_base(df):
    """
    Detecta la base estructural de un papel (para Warren Score v2 Pilar D).
    Retorna dict con semanas, prof, pos, voltrend — o None en cada campo si no computable.

    'minimo' y 'tramo_inicio' (agregados para el modificador de sacudon,
    Warren Score v3.1) exponen valores YA calculados internamente para
    profundidad/voltrend -- no cambian nada de lo que Pilar D usa ni de
    como se calculan semanas/prof/pos/voltrend.
    """
    NULL = {'semanas': None, 'prof': None, 'pos': None, 'voltrend': None,
            'minimo': None, 'tramo_inicio': None}
    try:
        if df is None or len(df) < 30:
            return NULL
        # Renombrar columnas a minúsculas para uniformidad
        df = df.copy()
        df.columns = [c.lower() for c in df.columns]
        if 'close' not in df.columns or 'high' not in df.columns:
            return NULL

        VENTANA = 130  # ~26 semanas
        reciente = df.tail(VENTANA)
        pivote_alto = reciente['high'].max()
        fecha_pivote = reciente['high'].idxmax()

        # Si el máximo está en las últimas 5 ruedas, retroceder al máximo previo
        if fecha_pivote >= df.index[-5]:
            reciente2 = df.iloc[:-5].tail(VENTANA)
            if len(reciente2) < 10:
                return NULL
            pivote_alto = reciente2['high'].max()
            fecha_pivote = reciente2['high'].idxmax()

        tramo = df.loc[fecha_pivote:]
        if len(tramo) < 10:
            return NULL

        min_base = tramo['low'].min()
        profundidad = (pivote_alto - min_base) / pivote_alto * 100

        # Sin corrección ≥6% = papel vertical sin base (caso CVS)
        if profundidad < 6:
            return NULL

        cierre = float(df['close'].iloc[-1])

        # ¿Rompió hace más de ~3 semanas?
        ruedas_sobre_pivote = int((tramo['close'] > pivote_alto).sum())
        if ruedas_sobre_pivote > 15:
            idx_bo = tramo[tramo['close'] > pivote_alto].index[0]
            tramo = df.loc[fecha_pivote:idx_bo]

        semanas = len(tramo) / 5.0
        posicion = (cierre - min_base) / (pivote_alto - min_base) * 100
        posicion = min(posicion, 130.0)  # clamp

        # Volumen decreciente: último tercio vs primer tercio del tramo,
        # EXCLUYENDO las ruedas más recientes (ahí el volumen sube por
        # definición si el papel está rompiendo o a punto de romper --
        # mismo bug de ventana contaminada ya corregido en verticalidad
        # reciente y en el detector de sacudón, Warren Score Pilar D
        # ajuste de VENTANA_EXCLUIDA/2026-08). Se usa MEDIANA en vez de
        # promedio: un earnings dentro de la base no debe distorsionar
        # el ratio con 1-2 outliers.
        VENTANA_EXCLUIDA_VOLTREND = 8  # calibrable 5-8
        tramo_voltrend = tramo.iloc[:-VENTANA_EXCLUIDA_VOLTREND] if len(tramo) > VENTANA_EXCLUIDA_VOLTREND else tramo.iloc[0:0]
        if 'volume' in df.columns and len(tramo_voltrend) >= 15:
            tercio_vt = max(5, len(tramo_voltrend) // 3)
            vol_ini = float(tramo_voltrend['volume'].iloc[:tercio_vt].median())
            vol_fin = float(tramo_voltrend['volume'].iloc[-tercio_vt:].median())
            voltrend = round(vol_fin / vol_ini, 2) if vol_ini > 0 else None
        else:
            voltrend = None

        return {
            'semanas':  round(semanas, 1),
            'prof':     round(profundidad, 1),
            'pos':      round(posicion, 1),
            'voltrend': voltrend,
            'minimo':       round(float(min_base), 2),
            'tramo_inicio': tramo.index[0],
        }
    except Exception as e:
        return NULL


def vol_trend_bloques(volume_series):
    """Vol Trend por bloques de 5 ruedas (Warren Score Pilar D, 2026-08).
    A diferencia del Vol Trend de detectar_base() (excluye la ventana
    reciente, mide si la BASE se secó), este mide el volumen EN VIVO,
    incluyendo la rueda actual -- para eso existe, para captar la
    expansion de volumen de un breakout real en curso.

    Ultimas 20 ruedas de volume_series (la ULTIMA fila es la rueda de
    referencia), partidas en 4 bloques de 5: 'reciente' (ultimas 5,
    incluye la rueda actual) vs el promedio de los 3 bloques anteriores
    (b1 mas cercano, b3 mas lejano). Mediana DENTRO de cada bloque (un
    dia raro no lo distorsiona), promedio ENTRE los 3 bloques de
    referencia (los tres pesan igual)."""
    if volume_series is None or len(volume_series) < 20:
        return None
    v = volume_series.tail(20)
    reciente = float(v.iloc[-5:].median())
    b1 = float(v.iloc[-10:-5].median())
    b2 = float(v.iloc[-15:-10].median())
    b3 = float(v.iloc[-20:-15].median())
    prom_b = (b1 + b2 + b3) / 3
    if prom_b <= 0:
        return None
    return round(reciente / prom_b, 4)


def _promedio_sin_outlier(valores):
    """Promedio de un bloque de 5 True Range, descartando el que más se
    desvía del promedio del propio bloque antes de promediar. Reacciona
    más rápido que la mediana (usa 4 de los 5 valores, no solo el del
    medio) sin que un único día de earnings/gap arruine el número --
    ese día es justamente el que más se desvía, y queda afuera."""
    m = sum(valores) / len(valores)
    idx_out = max(range(len(valores)), key=lambda i: abs(valores[i] - m))
    restantes = [v for i, v in enumerate(valores) if i != idx_out]
    return sum(restantes) / len(restantes)


def contraccion_volatilidad(hist):
    """Contracción de volatilidad de precio (Warren Score Pilar C, 2026-08;
    Bollinger BandWidth (length=10) reemplaza a True Range -- 2026-08-18,
    ver informe en wb_research/).

    BBW = (banda superior - banda inferior) / base * 100, con
    base=SMA(10) y banda=+-2*stdev(10) -- mide la DISPERSIÓN de los
    cierres respecto a su propia media móvil, no sólo el rango
    intradía+gaps rueda por rueda (True Range, la métrica anterior).
    Validado a escala (mismo contexto: reintento a un máximo previo, por
    encima de EMA200, medido el día del máximo, n=695): BBW es ~2-3x más
    fuerte que True Range en las 4 métricas de validación (Pearson
    -0.113 vs -0.054, Spearman -0.128 vs -0.046, spread de quintiles
    +3.96 vs +1.35 pts, spread zona-Tri +3.02 vs +2.31 pts) -- ver
    informe. La mayor tasa de éxito viene junto con menor tasa de
    fracaso (no es un promedio inflado por pocos ganadores grandes):
    62.3%→64.6% éxito y 23.6%→21.5% fracaso al entrar en zona.

    Mismo esqueleto reciente/referencia que la versión anterior (TR):
    serie diaria de BBW sobre las últimas 20 ruedas, partida en
    reciente=últimas 10 (vs) referencia=10 anteriores a esas (3 bloques
    de ~3-4 días, el de 4 con _promedio_sin_outlier). Ratio, no valor
    absoluto: mide ESTADO (¿más quieto que de costumbre?), no
    temperamento."""
    if hist is None or len(hist) < 30:
        return None
    try:
        close = hist['Close']
        sma10 = close.rolling(10).mean()
        std10 = close.rolling(10).std(ddof=0)
        mult = 2.0
        bbw = (2 * mult * std10 / sma10 * 100).dropna()
        if len(bbw) < 20:
            return None
        t = bbw.tail(20).tolist()
        reciente = _promedio_sin_outlier(t[-10:])
        ref = t[:-10]  # las 10 ruedas anteriores a las "recientes"
        bloque_1 = sum(ref[0:3]) / 3
        bloque_2 = sum(ref[3:6]) / 3
        bloque_3 = _promedio_sin_outlier(ref[6:10])
        referencia = (bloque_1 + bloque_2 + bloque_3) / 3
        if referencia <= 0:
            return None
        return round(reciente / referencia, 4)
    except Exception:
        return None


def direccionalidad_5r(df):
    """Direccionalidad 5r -- Warren Score v4.0, Paso 1/2. Eficiencia de
    Kaufman (adimensional, 0-1) sobre el bloque de 5 cierres previos a la
    rueda actual (la excluye a proposito): 1.0 = las 5 velas se movieron
    todas para el mismo lado (recorrido sin retrocesos), 0.0 =
    alternancia pura (vaiven en el mismo lugar). Usada como condicion de
    la penalizacion "Churning en resistencia" (Paso 2) -- el factor de
    direccionalidad que reduce el componente de Contraccion (Paso 1) usa
    una metrica distinta, ver avance_neto_bloque_5r_atrs()."""
    if df is None or len(df) < 6:
        return None
    try:
        bloque = df['Close'].iloc[-6:-1].tolist()
        cambios = [bloque[i] - bloque[i - 1] for i in range(1, len(bloque))]
        suma_abs = sum(abs(c) for c in cambios)
        if suma_abs == 0:
            return 0.0
        return round(abs(sum(cambios)) / suma_abs, 4)
    except Exception:
        return None


def avance_neto_bloque_5r_atrs(df, atr14_pct_valor, precio_actual):
    """Avance Neto Bloque 5r ATRs -- Warren Score v4.0, Paso 1 (v2, corrige
    el factor de direccionalidad original). El efficiency ratio de
    direccionalidad_5r() es adimensional: no distingue "marchar decidido"
    de "derivar apenas" (un papel que hace +-0.2 ATR de ida y vuelta puede
    dar el mismo ratio que uno que se movio 3 ATR derecho, si el camino
    fue igual de parejo). Esta metrica mide MAGNITUD, no forma: cuanto se
    movio el precio en limpio (extremo a extremo del bloque de 5 ruedas
    previas a hoy) medido en ATRs. Una pausa real casi no neto-avanza en
    ATRs aunque el camino haya sido derecho; un avance real si."""
    if df is None or len(df) < 6 or atr14_pct_valor is None or atr14_pct_valor <= 0 or precio_actual is None:
        return None
    try:
        atr_dolares = atr14_pct_valor / 100 * precio_actual
        if atr_dolares <= 0:
            return None
        close = df['Close']
        c_reciente = float(close.iloc[-2])
        c_viejo    = float(close.iloc[-6])
        return round(abs(c_reciente - c_viejo) / atr_dolares, 4)
    except Exception:
        return None


def resistencia_y_amplitud(df, atr14_pct_valor, precio_actual):
    """Dist Resistencia ATRs y Amplitud Bloque 5r ATRs -- Warren Score
    v4.0, Paso 2 (insumos de la penalizacion "Churning en resistencia").
    Resistencia = maximo de High de las 60 ruedas previas a la ventana
    reciente (excluye las ultimas 10 para no confundir el techo que el
    propio papel viene formando ahora con la resistencia contra la que
    choca). Amplitud = que tan ancho vino el bloque de 5 ruedas previas a
    hoy (excluye hoy, mismo criterio que direccionalidad_5r)."""
    NULO = {'Dist Resistencia ATRs': None, 'Amplitud Bloque 5r ATRs': None}
    if df is None or len(df) < 70 or atr14_pct_valor is None or atr14_pct_valor <= 0 or precio_actual is None:
        return NULO
    try:
        atr_dolares = atr14_pct_valor / 100 * precio_actual
        if atr_dolares <= 0:
            return NULO
        high, low = df['High'], df['Low']
        resistencia = float(high.iloc[-70:-10].max())
        dist_resistencia_atrs = round((resistencia - precio_actual) / atr_dolares, 2)
        bloque_high = high.iloc[-6:-1]
        bloque_low  = low.iloc[-6:-1]
        amplitud_atrs = round((float(bloque_high.max()) - float(bloque_low.min())) / atr_dolares, 2)
        return {'Dist Resistencia ATRs': dist_resistencia_atrs, 'Amplitud Bloque 5r ATRs': amplitud_atrs}
    except Exception:
        return NULO


def detectar_sacudon(hist, base, atr14_pct_valor):
    """Modificador de sacudon (shakeout) -- Warren Score v3.1.

    Antes de despegar, un papel que viene comprimiendo suele meter una
    sacudida violenta (barrida de stops / spring de Wyckoff) que el score
    castiga tres veces sin este modificador (compresion de corto, resta
    de verticalidad, resta de volatilidad sin direccion). Las 5
    condiciones deben cumplirse TODAS -- compresion previa valida es el
    prerrequisito absoluto; sin base no hay sacudon, es volatilidad comun.

    Devuelve tambien Vol Relativa / Vol 5d40d medidos en la ventana de 5
    ruedas ANTERIOR al inicio de la sacudida (reusando las funciones
    reales del pipeline, no reimplementadas) -- el frontend se queda con
    el mejor valor entre esa ventana y la de hoy, para que la sacudida no
    borre la compresion que el papel ya se habia ganado.
    """
    NULO = {'activo': False, 'ruedas': None, 'magnitud_atrs': None,
            'vol_relativa_pre': None, 'vol_5d40d_pre': None,
            'vol_trend_pre_sacudon': None, 'contraccion_vol_pre_sacudon': None}
    try:
        # 1) Compresion previa valida (prerrequisito absoluto) -----------
        # El voltrend de detectar_base() mide el ultimo tercio del tramo
        # COMPLETO hasta hoy -- si hay una sacudida real, sus propias velas
        # de volumen altisimo caen justo en ese ultimo tercio y contaminan
        # el promedio, inflando voltrend por encima de 1.0 y auto-vetando
        # el propio caso que la condicion deberia admitir. Por eso el gate
        # de compresion se recalcula excluyendo la ventana reciente donde
        # se busca la sacudida (misma formula tercio/tercio que usa
        # detectar_base, aplicada sobre tramo_base_ref mas abajo).
        if base is None or base.get('semanas') is None or base['semanas'] < 4:
            return NULO
        # Posicion alta en la base: un spring de Wyckoff ocurre con el
        # papel pegado al techo de su rango, listo para romper -- es lo
        # que distingue una sacudida constructiva (MRVL: precio arriba del
        # rango, sacude, sale) de una venta comun en un papel golpeado que
        # viene de abajo (BP/CVX/EQNR veniendo de caidas, no de un techo).
        if base.get('pos') is None or base['pos'] < 60:
            return NULO
        if base.get('minimo') is None or base.get('tramo_inicio') is None:
            return NULO
        if atr14_pct_valor is None or atr14_pct_valor <= 0:
            return NULO

        close  = hist['Close'].values
        high   = hist['High'].values
        low    = hist['Low'].values
        volume = hist['Volume'].values
        n = len(hist)
        if n < 30:
            return NULO

        precio_actual = float(close[-1])
        atr_dolares = atr14_pct_valor / 100 * precio_actual
        if atr_dolares <= 0:
            return NULO

        # Condicion 1 (compresion previa) y Condicion 5 (antiguedad de la
        # sacudida) usan ventanas DISTINTAS y no deben compartir constante:
        # la exclusion para el gate de compresion sigue siendo de 8 ruedas
        # (SIN CAMBIOS); la ventana de ESCANEO de candidatos se angosta a 4
        # (permite ruedas_desde hasta 3, el nuevo limite de Condicion 5) --
        # si se dejara en 8, el loop podria "romper" (break) en un
        # candidato viejo (ej. 7 ruedas atras) antes de llegar a uno mas
        # reciente y valido, y Condicion 5 lo descartaria sin haber
        # evaluado el candidato correcto.
        VENTANA_EXCLUSION_COMPRESION = min(8, n - 1)
        VENTANA_ESCANEO_SACUDIDA = min(4, n - 1)

        # Tramo de referencia DE LA BASE -- mismo tramo que uso
        # detectar_base, pero excluyendo la ventana reciente (donde se
        # busca la sacudida) para no contaminar el calculo con la propia
        # vela que se esta evaluando.
        tramo_base = hist.loc[base['tramo_inicio']:]
        tramo_base_ref = tramo_base.iloc[:-VENTANA_EXCLUSION_COMPRESION] if len(tramo_base) > VENTANA_EXCLUSION_COMPRESION else tramo_base.iloc[:0]
        if len(tramo_base_ref) < 5:
            return NULO

        # Voltrend "pre-sacudida": mismo concepto que detectar_base (ultimo
        # tercio vs primer tercio del tramo, ya excluyendo la ventana
        # reciente via tramo_base_ref), pero con MEDIANA en vez de promedio.
        # Un solo dia de earnings dentro de la base (volumen 5x un dia
        # puntual) no deberia invalidar una compresion real -- el promedio
        # es sensible a ese outlier, la mediana es inmune por construccion.
        # El umbral sigue siendo 1.0 con el mismo significado ("el volumen
        # venia secandose"); lo que cambia es solo el estimador.
        tercio_ref = max(5, len(tramo_base_ref) // 3)
        vol_ini_ref = float(tramo_base_ref['Volume'].iloc[:tercio_ref].median())
        vol_fin_ref = float(tramo_base_ref['Volume'].iloc[-tercio_ref:].median())
        if vol_ini_ref <= 0:
            return NULO
        voltrend_pre = round(vol_fin_ref / vol_ini_ref, 2)
        if voltrend_pre > 1.0:
            return NULO

        if n < 20:
            return NULO
        vol_prom_20 = float(pd.Series(volume).tail(20).mean())
        if vol_prom_20 <= 0:
            return NULO

        # 2) Retroceso violento PERO CONTENIDO + 4) Volumen alto + 5) Reciente.
        # Para cada candidato (vela o par) dentro de la ventana de escaneo:
        #   a) se ubica el ULTIMO MINIMO LOCAL CONFIRMADO (pivote con margen,
        #      no cualquier vela) y el maximo posterior a ese minimo -- eso
        #      define "el ultimo tramo alcista".
        #   b) ese tramo tiene que valer al menos 1.5 ATR en dolares -- un
        #      retroceso del 50% de un movimiento insignificante no es nada.
        #   c) el retroceso de la sacudida contra ese tramo tiene que ser
        #      >=50% (violento).
        #   d) CONTENIDO -- tres limites, TODOS obligatorios: la caida
        #      medida con el LOW no supera el 10% desde el cierre previo al
        #      evento (una mecha que perfora y recupera cuenta); el CIERRE
        #      del evento no perfora el minimo de las ultimas 2 semanas (10
        #      ruedas) previas; y el LOW del evento tampoco perfora el
        #      minimo de TODA la base (chequeo viejo, se mantiene como
        #      filtro adicional -- probado en vivo que sacarlo dejaba pasar
        #      falsos positivos en CVX/EQNR/ABNB, papeles con bases largas
        #      donde el minimo de 2 semanas por si solo es mucho mas laxo
        #      que el de la base entera).
        LOOKBACK_TRAMO = 30
        MARGEN_PIVOTE = 3
        idx_base_inicio = n - len(tramo_base)

        def _ultimo_tramo_alcista(idx_hasta):
            """Maximo reciente + ultimo minimo local confirmado antes de idx_hasta
            (ambos indices dentro de [idx_desde, idx_hasta)). None si no hay margen."""
            idx_desde = max(0, idx_hasta - LOOKBACK_TRAMO, idx_base_inicio)
            if idx_desde >= idx_hasta:
                return None
            pico_idx = idx_desde + int(np.argmax(high[idx_desde:idx_hasta]))
            minimo_local_idx = None
            for j in range(pico_idx - 1, idx_desde - 1, -1):
                lo = max(idx_desde, j - MARGEN_PIVOTE)
                hi = min(pico_idx, j + MARGEN_PIVOTE + 1)
                if low[j] <= low[lo:hi].min() + 1e-9:
                    minimo_local_idx = j
                    break
            if minimo_local_idx is None:
                minimo_local_idx = idx_desde
            tramo_dolares = float(high[pico_idx] - low[minimo_local_idx])
            return tramo_dolares, high[pico_idx]

        def _contenido(idx_inicio_cand, low_evento):
            """Condicion 2, partes (b) y (c): caida<10% desde el cierre previo
            (medida con el low, una mecha cuenta) y cierre del evento no
            perfora el minimo de las ultimas 2 semanas (10 ruedas) previas
            al inicio del evento. Devuelve (ok, minimo_2sem) o (False, None)."""
            if idx_inicio_cand < 1:
                return False, None
            cierre_previo = close[idx_inicio_cand - 1]
            if cierre_previo <= 0:
                return False, None
            caida_pct = (cierre_previo - low_evento) / cierre_previo * 100
            if caida_pct >= 10.0:
                return False, None
            ini_2sem = max(0, idx_inicio_cand - 10)
            if idx_inicio_cand <= ini_2sem:
                return False, None
            minimo_2sem = float(low[ini_2sem:idx_inicio_cand].min())
            return True, minimo_2sem

        sacudida_idx = None   # dia de referencia para "ruedas desde" (el mas reciente del evento)
        idx_inicio    = None   # dia en que arranca el evento (para truncar las series "pre")
        magnitud_bruta = None
        for i in range(n - VENTANA_ESCANEO_SACUDIDA, n):
            if i < 1:
                continue

            # -- vela individual --
            low_evento_vela = low[i]
            ok_contenido, minimo_2sem = _contenido(i, low_evento_vela)
            if ok_contenido and close[i] >= minimo_2sem and low_evento_vela > base['minimo']:
                r = _ultimo_tramo_alcista(i)
                if r is not None:
                    tramo_dolares, pico_valor = r
                    if tramo_dolares >= 1.5 * atr_dolares:  # (b)
                        retroceso = (pico_valor - low_evento_vela) / tramo_dolares
                        vol_vela_ok = volume[i] >= 1.3 * vol_prom_20  # Condicion 4 -- SIN CAMBIOS
                        if retroceso >= 0.5 and vol_vela_ok:  # (c) + volumen
                            sacudida_idx = i
                            idx_inicio = i
                            magnitud_bruta = max(high[i] - low[i], abs(low[i] - close[i - 1]))
                            break

            # -- par de 2 ruedas consecutivas --
            if i >= 2:
                low_evento_par = min(low[i - 1], low[i])
                ok_contenido, minimo_2sem = _contenido(i - 1, low_evento_par)
                if ok_contenido and close[i] >= minimo_2sem and low_evento_par > base['minimo']:
                    r = _ultimo_tramo_alcista(i - 1)
                    if r is not None:
                        tramo_dolares, pico_valor = r
                        if tramo_dolares >= 1.5 * atr_dolares:  # (b)
                            retroceso = (pico_valor - low_evento_par) / tramo_dolares
                            vol_par_ok = (volume[i - 1] + volume[i]) / 2 >= 1.3 * vol_prom_20  # Condicion 4 -- SIN CAMBIOS
                            if retroceso >= 0.5 and vol_par_ok:  # (c) + volumen
                                sacudida_idx = i
                                idx_inicio = i - 1
                                magnitud_bruta = max(
                                    max(high[i - 1], high[i]) - low_evento_par,
                                    abs(low_evento_par - close[i - 2])
                                )
                                break

        if sacudida_idx is None:
            return NULO

        # 5) Antiguedad y confirmacion alcista -- la sacudida tiene que ser
        # de hace <=3 ruedas; si pasaron exactamente 3 sin una vela alcista
        # (cierre>apertura) posterior, no califica (si el papel no
        # reacciona en 3 dias, no era el paso previo al despegue). Con
        # ruedas_desde<3 todavia hay margen, no se exige la vela alcista.
        ruedas_desde = (n - 1) - sacudida_idx
        if ruedas_desde > 3:
            return NULO
        if ruedas_desde >= 3:
            open_ = hist['Open'].values
            hubo_alcista = any(close[j] > open_[j] for j in range(sacudida_idx + 1, n))
            if not hubo_alcista:
                return NULO

        # Recuperacion -- condicion critica, NO negociable. El cierre
        # de hoy tiene que estar en o por encima del minimo de la base;
        # si no, es ruptura bajista real, no sacudon.
        if close[-1] < base['minimo']:
            return NULO

        magnitud_atrs = round(magnitud_bruta / atr_dolares, 2)

        # Vol Relativa / Vol 5d40d en la ventana pre-sacudida -- se
        # truncan las series justo ANTES de que arranque el evento
        # (idx_inicio, no sacudida_idx, para no incluir la primera vela del
        # par en la ventana "pre") y se reusan las funciones reales
        # (calcular_volatilidad_relativa ya hace .tail(5)/.tail(252)
        # internamente).
        vol_relativa_pre = calcular_volatilidad_relativa(
            pd.Series(close[:idx_inicio]), pd.Series(high[:idx_inicio]), pd.Series(low[:idx_inicio])
        )
        vol_5d40d_pre = None
        if idx_inicio >= 40:
            v5  = pd.Series(volume[:idx_inicio]).tail(5).mean()
            v40 = pd.Series(volume[:idx_inicio]).tail(40).mean()
            if v40 > 0:
                vol_5d40d_pre = round(float(v5 / v40), 2)

        # Vol Trend pre-sacudon (por bloques, Parte 1 del spec) -- misma
        # formula que vol_trend_bloques() pero con la serie de volumen
        # cortada justo antes de que arranque el evento (idx_inicio), para
        # que el frontend pueda dar el bono completo de Pilar D cuando el
        # papel venia comprimiendo antes de la sacudida.
        vol_trend_pre_sacudon = vol_trend_bloques(pd.Series(volume[:idx_inicio]))

        # Contraccion de volatilidad pre-sacudon (Pilar C, 2026-08) --
        # mismo criterio: el TR de la sacudida infla el ratio en vivo por
        # encima del sweet spot (rango violento = "expandiendose", 0 pts)
        # justo cuando se quiere premiar la compresion que ya se habia
        # ganado antes del evento. Se corta la serie antes de idx_inicio.
        contraccion_vol_pre_sacudon = contraccion_volatilidad(hist.iloc[:idx_inicio])

        return {
            'activo': True, 'ruedas': ruedas_desde, 'magnitud_atrs': magnitud_atrs,
            'vol_relativa_pre': vol_relativa_pre, 'vol_5d40d_pre': vol_5d40d_pre,
            'vol_trend_pre_sacudon': vol_trend_pre_sacudon,
            'contraccion_vol_pre_sacudon': contraccion_vol_pre_sacudon,
        }
    except Exception:
        return NULO


def div_rsi(hist):
    """Divergencia bajista de RSI: precio hace máximos nuevos pero RSI no los confirma."""
    try:
        if hist is None or len(hist) < 20:
            return False
        close = hist['Close']
        delta = close.diff()
        # Wilder's Smoothing (RMA) -- igual a calcular_rsi() y a ta.rma de TradingView.
        # (antes usaba rolling().mean(), una SMA simple que da valores distintos)
        gain  = delta.clip(lower=0).ewm(alpha=1/14, min_periods=14, adjust=False).mean()
        loss  = (-delta.clip(upper=0)).ewm(alpha=1/14, min_periods=14, adjust=False).mean()
        rsi   = (100 - 100 / (1 + gain / loss.replace(0, np.nan))).values
        c     = close.values
        n     = min(40, len(c))
        cw, rw = c[-n:], rsi[-n:]
        # Pivotes confirmados: máximo local con ≥4 ruedas de margen a cada lado
        pivots = [i for i in range(4, n - 4)
                  if all(cw[i] >= cw[i-j] for j in range(1, 5))
                  and all(cw[i] >= cw[i+j] for j in range(1, 5))]
        if len(pivots) < 2:
            return False
        p1, p2 = pivots[-2], pivots[-1]
        if np.isnan(rw[p1]) or np.isnan(rw[p2]):
            return False
        if not bool(cw[p2] > cw[p1] and rw[p2] < rw[p1] - 3):
            return False

        # Anulación: si en las últimas 5 ruedas el precio ya superó el último
        # pivote confirmado y el RSI lo acompañó (no cayó ≥3 pts), el avance
        # reciente objeta la divergencia vieja aunque todavía no sea un
        # pivote "confirmado" (le faltan ruedas futuras para serlo)
        recientes     = cw[-5:]
        rsi_recientes = rw[-5:]
        idx_max       = int(np.argmax(recientes))
        max_reciente  = recientes[idx_max]
        rsi_en_max    = rsi_recientes[idx_max]
        if not np.isnan(rsi_en_max) and max_reciente > cw[p2] and rsi_en_max >= rw[p2] - 3:
            return False

        return True
    except:
        return False


def div_obv(hist, R=3, L=20):
    """'Suba sin combustible' (reemplaza la vieja divergencia de OBV de dos ventanas):
    el precio sigue haciendo maximos pegado al pico de las ultimas L ruedas, pero con
    velas mas chicas y volumen mas seco que el impulso que marco ese pico. Distingue
    agotamiento (sigue subiendo sin fuerza) de compresion sana (lateraliza/corrige)."""
    try:
        if hist is None or len(hist) < L + R + 2:
            return False
        c = hist['Close'].values
        h = hist['High'].values
        l = hist['Low'].values
        v = hist['Volume'].values
        n = len(hist)

        # pico = indice del dia de mayor volumen en las ultimas L ruedas (el impulso real,
        # no el maximo de High — asi no se corre dia a dia mientras el precio hace
        # maximos marginales con volumen decreciente)
        ini  = n - L
        pico = ini + int(np.argmax(v[ini:]))

        # si el pico es demasiado reciente, no hay "despues" que evaluar
        if pico > n - 1 - R:
            return False

        # 1) sigue arriba pero avanza poco (y no se derrumba)
        avance_reciente = (c[-1] - c[-1 - R]) / c[-1 - R] * 100
        cond1 = (c[-1] >= h[pico] * 0.97) and (-3.0 < avance_reciente < 3.5)

        # 2) velas mas chicas que en el impulso
        rango = h - l
        rango_reciente = rango[-R:].mean()
        rango_impulso  = rango[pico - R + 1: pico + 1].mean()
        cond2 = rango_impulso > 0 and (rango_reciente / rango_impulso) < 0.65

        # 3) volumen secandose respecto del impulso
        vol_reciente = v[-R:].mean()
        vol_impulso  = v[pico - R + 1: pico + 1].mean()
        cond3 = vol_impulso > 0 and (vol_reciente / vol_impulso) < 0.70

        return bool(cond1 and cond2 and cond3)
    except:
        return False


# ── Agotamiento OBV v2 -- penalizaciones nuevas, separadas del bloque
# "Agotamiento" original (Warren Score v4.2). Investigación completa y
# validación a escala documentadas en
# wb_research/analisis_mu_fcx_bhp/INFORME_eficiencia_kaufman_dia_maximo.md
# -- NO tocar sin revisar ese informe primero.
#
# div_obv_v2 es una variante de div_obv (arriba) con 3 cambios pedidos y
# validados por separado: ventana del impulso más corta (10 en vez de 20
# ruedas), banda "cerca del pico" más ancha (5% en vez de 3%) y la
# condición 1 exige avance reciente estrictamente >=0 (solo "sigue
# subiendo tibio", no "está corrigiendo con volumen seco" -- eso se
# considera descanso sano, no agotamiento). div_obv (la original) NO se
# toca -- sigue alimentando el bloque "Agotamiento" existente tal cual.
def div_obv_v2(hist, R=3, L=10, banda_pico=0.05, techo_avance=3.5):
    try:
        if hist is None or len(hist) < L + R + 2:
            return False
        c = hist['Close'].values
        h = hist['High'].values
        l = hist['Low'].values
        v = hist['Volume'].values
        n = len(hist)
        ini = n - L
        pico = ini + int(np.argmax(v[ini:]))
        if pico > n - 1 - R:
            return False
        avance_reciente = (c[-1] - c[-1 - R]) / c[-1 - R] * 100
        cond1 = (c[-1] >= h[pico] * (1 - banda_pico)) and (0 <= avance_reciente < techo_avance)
        rango = h - l
        rango_reciente = rango[-R:].mean()
        rango_impulso = rango[pico - R + 1: pico + 1].mean()
        cond2 = rango_impulso > 0 and (rango_reciente / rango_impulso) < 0.65
        vol_reciente = v[-R:].mean()
        vol_impulso = v[pico - R + 1: pico + 1].mean()
        cond3 = vol_impulso > 0 and (vol_reciente / vol_impulso) < 0.70
        return bool(cond1 and cond2 and cond3)
    except Exception:
        return False


OBV_LOOKBACK_MAXIMO = 90   # ruedas hacia atrás para buscar el inicio del episodio actual --
                           # límite práctico de búsqueda, NO un tope de duración: si el episodio
                           # sigue sin resolverse dentro de esta ventana, se sigue penalizando.


def agotamiento_obv_v2(hist, hist_spy):
    """
    Estado "pegajoso" (Warren Score v4.4): a diferencia de la versión
    anterior (que se re-evaluaba día a día y se apagaba apenas UNA de las
    3 condiciones originales dejaba de cumplirse -- visto en vivo con
    NVDA: se apagó con solo 1 día de corrección, sin ninguna señal de
    recuperación real), ahora una vez que arranca el episodio se
    mantiene penalizando SIN TOPE DE DÍAS hasta que se confirma una
    recuperación real -- las 5 condiciones siguientes a la vez, el mismo
    día:
      1. Al menos una de las 3 condiciones originales de Div OBV v2 ya
         no se cumple (el patrón técnico se disolvió)
      2. Cierre de hoy > cierre de ayer
      3. RVOL10 >= 1 (volumen real, no seco)
      4. RS Score de hoy > RS Score de ayer (fuerza relativa mejorando)
      5. Cierre de hoy > SMA10
    'combo_penaliza' (más severo) es el mismo episodio, pero marcado
    como tal si Div RSI (divergencia RSI) TAMBIÉN estaba activa el día
    que arrancó el episodio -- comparte el mismo día de inicio y la
    misma condición de liberación que 'obv_penaliza', no es una máquina
    de estados separada.
    Sin estado persistido entre corridas: se recalcula desde el
    histórico completo cada vez, simulando hacia adelante desde el
    inicio del episodio más reciente encontrado dentro de
    OBV_LOOKBACK_MAXIMO ruedas.
    """
    resultado = {'obv_penaliza': False, 'obv_dias': None, 'obv_fecha_inicio': None,
                 'combo_penaliza': False}
    try:
        n = len(hist)
        if n < 260 + OBV_LOOKBACK_MAXIMO:
            return resultado

        close = hist['Close'].values
        vol = hist['Volume'].values
        vol_sma10_prior = pd.Series(vol).shift(1).rolling(10).mean().values
        rvol10 = vol / vol_sma10_prior
        sma10_serie = hist['Close'].rolling(10).mean().values

        idx_ini = n - OBV_LOOKBACK_MAXIMO
        _cache_obv = {}
        _cache_rsi = {}
        _cache_rs = {}

        def _obv(idx):
            if idx not in _cache_obv:
                _cache_obv[idx] = div_obv_v2(hist.iloc[:idx + 1])
            return _cache_obv[idx]

        def _rsi_div(idx):
            if idx not in _cache_rsi:
                _cache_rsi[idx] = bool(div_rsi(hist.iloc[:idx + 1]))
            return _cache_rsi[idx]

        def _rs_hoy_ayer(idx):
            if idx not in _cache_rs:
                sub_close = hist['Close'].iloc[:idx + 1]
                sub_spy = hist_spy['Close'].loc[:hist.index[idx]]
                r = calcular_rs_score(sub_close, sub_spy)
                _cache_rs[idx] = (r[0], r[1])  # (score_actual, score_ayer)
            return _cache_rs[idx]

        activo = False
        inicio_idx = None
        combo = False

        for idx in range(idx_ini, n):
            if not activo:
                if _obv(idx):
                    activo = True
                    inicio_idx = idx
                    combo = _rsi_div(idx)
                continue

            # episodio activo -- chequear las 5 condiciones de recuperación
            cond1 = not _obv(idx)
            cierre_hoy = close[idx]
            cierre_ayer = close[idx - 1] if idx > 0 else None
            cond2 = cierre_ayer is not None and cierre_hoy > cierre_ayer
            r10 = rvol10[idx]
            cond3 = not np.isnan(r10) and r10 >= 1.0
            sc_hoy, sc_ayer = _rs_hoy_ayer(idx)
            cond4 = sc_hoy is not None and sc_ayer is not None and sc_hoy > sc_ayer
            s10 = sma10_serie[idx]
            cond5 = not np.isnan(s10) and cierre_hoy > s10

            if cond1 and cond2 and cond3 and cond4 and cond5:
                activo = False
                inicio_idx = None
                combo = False

        if activo and inicio_idx is not None:
            resultado['obv_penaliza'] = True
            resultado['obv_dias'] = (n - 1) - inicio_idx
            resultado['obv_fecha_inicio'] = str(hist.index[inicio_idx].date())
            resultado['combo_penaliza'] = bool(combo)

        return resultado
    except Exception:
        return {'obv_penaliza': False, 'obv_dias': None, 'obv_fecha_inicio': None, 'combo_penaliza': False}


def churn_maximos(hist):
    """Churning en máximos: ≥3 días en las últimas 10 ruedas con cierre en mitad inferior y volumen ≥50% sobre el promedio de esas 10 ruedas."""
    try:
        if hist is None or len(hist) < 25:
            return False
        hi  = hist['High'].values
        lo  = hist['Low'].values
        c   = hist['Close'].values
        v   = hist['Volume'].values
        max_20 = hi[-20:].max()
        if max_20 <= 0 or (max_20 - c[-1]) / max_20 * 100 > 4:
            return False
        vol_avg = v[-10:].mean()
        if vol_avg <= 0:
            return False
        count = sum(
            1 for i in range(-10, 0)
            if (hi[i] - lo[i]) > 0
            and (c[i] - lo[i]) / (hi[i] - lo[i]) < 0.5
            and v[i] >= vol_avg * 1.5
        )
        return count >= 3
    except:
        return False


def _detectar_vcp_raw(hist, pivot_order=3):
    try:
        h = hist['High'].values
        l = hist['Low'].values
        c = hist['Close'].values
        v = hist['Volume'].values
        # Últimas 90 ruedas
        if len(c) > 90:
            h = h[-90:]; l = l[-90:]; c = c[-90:]; v = v[-90:]
        if len(c) < 30:
            return {'VCP Score': None, 'VCP Detected': False, 'VCP Contractions': 0,
                    'VCP Tightness': None, 'VCP Dist Pivot %': None, 'VCP Vol Decreasing': False,
                    'VCP Techo Toques': None, 'VCP Techo': None}

        def find_pivots(arr, order, mode):
            pivots = []
            for i in range(order, len(arr) - order):
                w = arr[i-order:i+order+1]
                if mode == 'H' and arr[i] >= max(w):
                    pivots.append((i, float(arr[i])))
                elif mode == 'L' and arr[i] <= min(w):
                    pivots.append((i, float(arr[i])))
            return pivots

        ph = find_pivots(h, pivot_order, 'H')
        pl = find_pivots(l, pivot_order, 'L')

        if not ph or not pl:
            return {'VCP Score': 0, 'VCP Detected': False, 'VCP Contractions': 0,
                    'VCP Tightness': None, 'VCP Dist Pivot %': None, 'VCP Vol Decreasing': False,
                    'VCP Techo Toques': None, 'VCP Techo': None}

        all_piv = [(i, 'H', val) for i, val in ph] + [(i, 'L', val) for i, val in pl]
        all_piv.sort()

        # Cada máximo es candidato a inicio de su propia contracción: busca el
        # primer mínimo siguiente, salteando máximos MENORES en el camino; si
        # aparece un máximo MAYOR antes de encontrar el mínimo, este máximo
        # queda superado por ese techo más alto y no arranca contracción.
        # (el emparejamiento secuencial anterior saltaba el índice hasta el
        # mínimo encontrado, dejando "huérfanos" a los máximos intermedios —
        # nunca se evaluaban como inicio de su propia contracción)
        candidatos = []
        for k in range(len(all_piv)):
            if all_piv[k][1] != 'H':
                continue
            hi, _, hval = all_piv[k]
            li = lval = None
            for j in range(k + 1, len(all_piv)):
                jidx, jkind, jval = all_piv[j]
                if jkind == 'H':
                    if jval > hval:
                        li = None
                        break
                    continue
                li, lval = jidx, jval
                break
            if li is not None and hval > lval:
                seg_vol = float(np.mean(v[hi:li+1])) if li > hi else float(v[hi])
                candidatos.append({'hi_idx': hi, 'li_idx': li, 'high': hval, 'low': lval,
                                    'pct': (hval - lval) / hval * 100, 'avg_vol': seg_vol})

        # Si dos candidatos terminan en el mismo mínimo (un máximo menor
        # "saltado" también llega al mismo mínimo), se queda el que arranca
        # en el máximo más alto — es el techo relevante.
        por_low = {}
        for ct in candidatos:
            actual = por_low.get(ct['li_idx'])
            if actual is None or ct['high'] > actual['high']:
                por_low[ct['li_idx']] = ct
        contractions = sorted(por_low.values(), key=lambda ct: ct['hi_idx'])

        if len(contractions) < 2:
            return {'VCP Score': 0, 'VCP Detected': False, 'VCP Contractions': len(contractions),
                    'VCP Tightness': None, 'VCP Dist Pivot %': None, 'VCP Vol Decreasing': False,
                    'VCP Techo Toques': None, 'VCP Techo': None}

        # El techo es el nivel más TESTEADO (más toques), no el más reciente ni
        # el más alto -- pero tiene que ser una resistencia a ROMPER: al nivel
        # del precio actual o por encima (2% de margen para el caso "recién
        # roto"), y vigente (no más de 30% arriba, para no elegir un máximo
        # viejo e irrelevante de cuando el papel cotizaba a otro precio).
        # Tolerancia de toques adaptada al ATR: un % fijo es demasiado
        # apretado para un papel volátil y demasiado laxo para uno tranquilo.
        atr_hist  = atr14_pct(hist)
        TOL_TOQUE = max(0.02, 0.008 * atr_hist) if atr_hist else 0.025
        niveles   = [val for _, val in ph]

        def _contar_toques(nivel):
            return sum(1 for v in niveles if abs(v - nivel) / nivel <= TOL_TOQUE)

        precio_actual = float(c[-1])
        # Elegibilidad del techo evaluada contra el MENOR precio de hoy/ayer
        # (no solo hoy): un breakout con gap fuerte (>~2%) empuja precio_actual
        # bien por encima del techo real y lo deja afuera de la tolerancia el
        # mismo dia que deberia confirmarse -- justo cuando mas importa (caso
        # NVDA 8/1/2024: VCP Score 100 -> 0 en la rueda del breakout). Usar
        # tambien el cierre de ayer (pre-gap) le da al techo un dia de gracia
        # sin tocar el resto de la logica (dist_pivot sigue midiendose contra
        # precio_actual, sin cambios).
        precio_ref    = min(precio_actual, float(c[-2])) if len(c) >= 2 else precio_actual
        rango_valido  = [(idx_h, val_h) for idx_h, val_h in ph
                         if precio_ref * 0.98 <= val_h <= precio_actual * 1.30]
        candidatos_techo = [(idx_h, val_h, _contar_toques(val_h)) for idx_h, val_h in rango_valido]
        con_toques = [ct for ct in candidatos_techo if ct[2] >= 2]

        if con_toques:
            max_toques = max(ct[2] for ct in con_toques)
            mejores    = [ct for ct in con_toques if ct[2] == max_toques]
            techo_idx, techo, techo_toques = min(mejores, key=lambda ct: ct[1])
        elif candidatos_techo:
            # Ningún nivel junta 2 toques: una resistencia de un solo toque es
            # débil, pero no es ausencia de patrón -- el score sigue su curso
            # normal, el componente de calidad de resistencia no suma puntos.
            techo_idx, techo, techo_toques = max(candidatos_techo, key=lambda ct: ct[1])
        else:
            return {'VCP Score': 0, 'VCP Detected': False, 'VCP Contractions': len(contractions),
                    'VCP Tightness': None, 'VCP Dist Pivot %': None, 'VCP Vol Decreasing': False,
                    'VCP Techo Toques': 0, 'VCP Techo': None}

        # Delimitar la base: ancla en la ÚLTIMA CONTRACCIÓN real (no en el
        # techo elegido por toques -- ese puede ser un máximo antiguo sin
        # contracción propia asociada dentro de la ventana, lo que dejaría la
        # lista vacía si el precio lo tocó apenas de pasada más tarde).
        # Camina hacia atrás desde ahí mientras el precio no supere el
        # máximo de esa última contracción (con el mismo margen de tolerancia
        # ATR-adaptado que el techo, TOL_TOQUE) ni caiga más de ~37% respecto
        # de él. Descarta contracciones previas al inicio de la base
        # (arrastradas por la ventana de 90 ruedas pero ajenas al patrón) y
        # las que sean ruido relativo al rango de esa base (<20% del rango).
        #
        # El margen de tolerancia importa: sin él, la contracción PENÚLTIMA
        # de un VCP legítimo casi siempre queda excluida en cuanto se agrega
        # una barra nueva -- por diseño, cada contracción tiene un máximo un
        # poco más alto que la siguiente (eso ES la contracción), así que
        # "no superar el máximo de la última" se dispara con la contracción
        # vecina de inmediato y la base entera pierde el ancla (caso NVDA
        # 8/1/2024: al confirmarse una contracción nueva al cierre del gap,
        # la contracción previa -apenas 0.9% más alta- quedaba afuera y
        # `contractions` caía de 2 a 1, tirando el score a 0 justo el día
        # del breakout).
        MAX_CAIDA_BASE = 0.37
        base_idx  = contractions[-1]['hi_idx']
        base_high = contractions[-1]['high']
        inicio_base = 0
        for k in range(base_idx - 1, -1, -1):
            if c[k] > base_high * (1 + TOL_TOQUE) or c[k] < base_high * (1 - MAX_CAIDA_BASE):
                inicio_base = k + 1
                break

        contractions = [ct for ct in contractions if ct['hi_idx'] >= inicio_base]
        if len(contractions) < 2:
            return {'VCP Score': 0, 'VCP Detected': False, 'VCP Contractions': len(contractions),
                    'VCP Tightness': None, 'VCP Dist Pivot %': None, 'VCP Vol Decreasing': False,
                    'VCP Techo Toques': techo_toques, 'VCP Techo': round(techo, 2)}

        rango_base_abs = base_high - float(np.min(l[inicio_base:base_idx + 1]))
        if rango_base_abs > 0:
            contractions = [ct for ct in contractions
                             if (ct['high'] - ct['low']) / rango_base_abs >= 0.20]
        if len(contractions) < 2:
            return {'VCP Score': 0, 'VCP Detected': False, 'VCP Contractions': len(contractions),
                    'VCP Tightness': None, 'VCP Dist Pivot %': None, 'VCP Vol Decreasing': False,
                    'VCP Techo Toques': techo_toques, 'VCP Techo': round(techo, 2)}

        pcts = [ct['pct'] for ct in contractions]
        vols = [ct['avg_vol'] for ct in contractions]
        n_c  = len(contractions)
        pairs = n_c - 1

        pct_dec = sum(1 for k in range(pairs) if pcts[k] > pcts[k+1]) / pairs
        vol_dec = sum(1 for k in range(pairs) if vols[k] > vols[k+1]) / pairs

        last_pct   = pcts[-1]
        dist_pivot = (float(c[-1]) - techo) / techo * 100

        score = 0
        score += round(pct_dec * 35)
        score += round(vol_dec * 20)
        if last_pct <= 5:    score += 20
        elif last_pct <= 10: score += 15
        elif last_pct <= 15: score += 10
        elif last_pct <= 20: score += 5
        if   -3  <= dist_pivot <= 1:   score += 15
        elif -5  <= dist_pivot < -3:   score += 12
        elif -8  <= dist_pivot < -5:   score += 8
        elif -15 <= dist_pivot < -8:   score += 4
        if n_c >= 4:   score += 10
        elif n_c == 3: score += 7
        elif n_c == 2: score += 4
        # Calidad de la resistencia: cuantos mas toques valido el techo, mas
        # significativa es la ruptura.
        if   techo_toques >= 5: score += 12
        elif techo_toques == 4: score += 10
        elif techo_toques == 3: score += 8
        elif techo_toques == 2: score += 5
        score = min(100, score)

        return {
            'VCP Score':          score,
            'VCP Detected':       score >= 55,
            'VCP Contractions':   n_c,
            'VCP Tightness':      round(last_pct, 2),
            'VCP Dist Pivot %':   round(dist_pivot, 2),
            'VCP Vol Decreasing': vol_dec >= 0.5,
            'VCP Techo Toques':   techo_toques,
            'VCP Techo':          round(techo, 2),
        }
    except:
        return {'VCP Score': None, 'VCP Detected': False, 'VCP Contractions': 0,
                'VCP Tightness': None, 'VCP Dist Pivot %': None, 'VCP Vol Decreasing': False,
                'VCP Techo Toques': None, 'VCP Techo': None}


def detectar_vcp(hist, pivot_order=3, hyst_dias=2, ventana_hyst=6):
    """Envoltorio con histeresis sobre 'VCP Detected': exige `hyst_dias`
    sesiones consecutivas por encima (o por debajo) del umbral 55 antes de
    prender (o apagar) la deteccion. El recalculo de pivotes dia a dia hace
    que VCP Score oscile +-6/7 pts sin que la base cambie de verdad -- eso
    hacia parpadear 'VCP Detected' 13-17 veces durante una base legitima
    (casos NVDA/MRVL). El resto de los campos (Score, Tightness, Dist Pivot,
    etc.) se devuelven crudos, sin suavizar -- solo el booleano 'Detected'
    tiene memoria de corto plazo."""
    actual = _detectar_vcp_raw(hist, pivot_order)
    if actual['VCP Score'] is None:
        return actual
    n = len(hist)
    ventana = min(ventana_hyst, n - 30)
    if ventana < hyst_dias:
        return actual
    detected = False
    streak_on = streak_off = 0
    for k in range(ventana, -1, -1):
        idx_hasta = n - k
        if idx_hasta < 30:
            continue
        raw = _detectar_vcp_raw(hist.iloc[:idx_hasta], pivot_order)
        s = raw['VCP Score'] or 0
        if s >= 55:
            streak_on += 1; streak_off = 0
        else:
            streak_off += 1; streak_on = 0
        if streak_on  >= hyst_dias: detected = True
        if streak_off >= hyst_dias: detected = False
    actual = dict(actual)
    actual['VCP Detected'] = detected
    return actual

def calcular_sesiones_10(close, volume):
    """
    Últimas 10 sesiones: días positivos/negativos y volumen acumulado por tipo.
    Un día es positivo si cierre > cierre anterior.
    """
    if len(close) < 11 or len(volume) < 10:
        return None, None, None, None
    precios = close.tail(11).values
    vols    = volume.tail(10).values
    dias_pos, dias_neg = 0, 0
    vol_pos,  vol_neg  = 0.0, 0.0
    for i in range(10):
        cambio = precios[i + 1] - precios[i]
        v      = float(vols[i])
        if cambio > 0:
            dias_pos += 1
            vol_pos  += v
        elif cambio < 0:
            dias_neg += 1
            vol_neg  += v
    return dias_pos, dias_neg, round(vol_pos), round(vol_neg)

